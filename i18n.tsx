export const getFullDayColumnLabelKey = (day: DayColumnId): TranslationKey => {
  const keys: Record<DayColumnId, TranslationKey> = {
    mon: 'column.monday',
    tue: 'column.tuesday',
    wed: 'column.wednesday',
    thu: 'column.thursday',
    fri: 'column.friday',
    sat: 'column.saturday',
    sun: 'column.sunday',
  };
  return keys[day];
};

export const getFullDayLabelKey = (dayIndex: number): TranslationKey => {
  const keys: TranslationKey[] = [
    'column.sunday',
    'column.monday',
    'column.tuesday',
    'column.wednesday',
    'column.thursday',
    'column.friday',
    'column.saturday',
  ];
  return keys[dayIndex] ?? 'column.monday';
};

export const getPriorityLabelKey = (priority: Priority): TranslationKey => {
  if (priority === Priority.Marginal) return 'priority.marginal';
  if (priority === Priority.Helpful) return 'priority.helpful';
  if (priority === Priority.Necessary) return 'priority.necessary';
  if (priority === Priority.Critical) return 'priority.critical';
  return 'priority.important';
};

export const getReflectionLabelKey = (value: ReflectionValue): TranslationKey => {
  if (value === ReflectionValue.NotUseful) return 'reflection.notUseful';
  if (value === ReflectionValue.SomewhatUseful) return 'reflection.somewhatUseful';
  return 'reflection.useful';
};
