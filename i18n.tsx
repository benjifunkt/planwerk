const dictionaries: Record<ResolvedLanguage, Record<TranslationKey, string>> = {
  en,
  de,
};

type TranslationParams = Record<string, string | number>;

export type TFunction = (key: TranslationKey, params?: TranslationParams) => string;

interface I18nContextValue {
  language: ResolvedLanguage;
  languageSetting: Language;
  locale: string;
  t: TFunction;
}

const I18nContext = createContext<I18nContextValue | null>(null);

const languageToLocale = (language: ResolvedLanguage) => (
  language === 'de' ? 'de-DE' : 'en-US'
);

const getBrowserLanguages = (): readonly string[] => {
  if (typeof navigator === 'undefined') return [];
  if (Array.isArray(navigator.languages) && navigator.languages.length > 0) {
    return navigator.languages;
  }
  return navigator.language ? [navigator.language] : [];
};

const detectSystemLanguage = (): ResolvedLanguage => {
  const match = getBrowserLanguages().find(language => {
    const normalized = language.toLowerCase();
    return normalized.startsWith('de') || normalized.startsWith('en');
  });

  if (match?.toLowerCase().startsWith('de')) return 'de';
  return 'en';
};

export const resolveLanguage = (languageSetting: Language = 'system'): ResolvedLanguage => {
  if (languageSetting === 'de' || languageSetting === 'en') return languageSetting;
  return detectSystemLanguage();
};

const translate = (language: ResolvedLanguage, key: TranslationKey, params?: TranslationParams): string => {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  if (!params) return template;

  return Object.entries(params).reduce((result, [paramKey, value]) => (
    result.replaceAll(`{${paramKey}}`, String(value))
  ), template);
};

export const I18nProvider: React.FC<{ languageSetting?: Language; children: ReactNode }> = ({
  languageSetting = 'system',
  children,
}) => {
  const [systemLanguage, setSystemLanguage] = useState<ResolvedLanguage>(() => detectSystemLanguage());

  useEffect(() => {
    if (languageSetting !== 'system') return;

    const handleLanguageChange = () => setSystemLanguage(detectSystemLanguage());
    window.addEventListener('languagechange', handleLanguageChange);
    return () => window.removeEventListener('languagechange', handleLanguageChange);
  }, [languageSetting]);

  const language = languageSetting === 'system' ? systemLanguage : resolveLanguage(languageSetting as Language);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    languageSetting,
    locale: languageToLocale(language),
    t: (key, params) => translate(language, key, params),
  }), [language, languageSetting]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return context;
};

